"""Build the CSS the app consumes from the token sources.

Inputs (source of truth, edit these):
  design/tokens/tokens.color.json   generated by tools/palette.py (run that first if colors change)
  design/tokens/tokens.base.json    type, space, radius, layout, motion, aspect, z

Outputs (generated, never edit by hand):
  design/tokens/build/tokens.css          CSS custom properties on :root
  design/tokens/build/wire.css            wireframe mode: [data-mode="wire"] greyscale overrides
  design/tokens/build/tailwind-theme.css  Tailwind v4 @theme block mapped to the variables

Usage: python3 tools/build_tokens.py
"""
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
SRC = os.path.join(ROOT, "design", "tokens")
OUT = os.path.join(SRC, "build")


def load(name):
    with open(os.path.join(SRC, name)) as f:
        return json.load(f)


def flatten(node, prefix=""):
    """Yield (name, value) for every token leaf ({"$value": ...})."""
    for k, v in node.items():
        if k.startswith("$"):
            continue
        name = f"{prefix}-{k}" if prefix else k
        if isinstance(v, dict) and "$value" in v:
            yield name, v["$value"]
        elif isinstance(v, dict):
            yield from flatten(v, name)


def css_value(v):
    if isinstance(v, list):  # cubic-bezier
        return "cubic-bezier(" + ", ".join(str(x) for x in v) + ")"
    return str(v)


def main():
    os.makedirs(OUT, exist_ok=True)
    color = load("tokens.color.json")["color"]
    base = load("tokens.base.json")

    lines = ["/* GENERATED by tools/build_tokens.py. Do not edit. */", ":root {"]
    for name, v in flatten(color, "color"):
        if v == "TBC":
            continue
        # semantic roles live in the --color-* namespace: --color-surface-page, --color-text-primary ...
        name = name.replace("color-role-", "color-")
        lines.append(f"  --{name}: {v};")
    for group in ("font", "space", "radius", "border", "layout", "motion", "aspect", "z", "breakpoint"):
        for name, v in flatten(base[group], group):
            if group == "motion" and name.endswith("reduced"):
                continue
            lines.append(f"  --{name}: {css_value(v)};")
    lines.append("}")
    lines.append("")
    lines.append("@media (prefers-reduced-motion: reduce) {")
    lines.append("  :root { --motion-fast: 0ms; --motion-base: 150ms; --motion-slow: 150ms; }")
    lines.append("}")
    with open(os.path.join(OUT, "tokens.css"), "w") as f:
        f.write("\n".join(lines) + "\n")

    # Wireframe mode: same components, greyscale roles, no brand color.
    ink = {k: v["$value"] for k, v in color["ink"].items()}
    wire = {
        "surface-page": "#FFFFFF", "surface-raised": "#FFFFFF", "surface-sunken": ink["100"],
        "surface-inverse": ink["800"], "surface-brand": ink["600"],
        "text-primary": "#000000", "text-secondary": ink["700"], "text-muted": ink["600"],
        "text-on-inverse": "#FFFFFF", "text-on-brand": "#FFFFFF", "text-link": "#000000",
        "text-sale": "#000000", "text-success": "#000000", "text-low-stock": "#000000",
        "text-sale-on-inverse": "#FFFFFF", "text-success-on-inverse": "#FFFFFF",
        "border-hairline": ink["300"], "border-control": ink["500"], "border-strong": "#000000",
        "action-primary": ink["800"], "action-primary-hover": ink["900"], "action-primary-pressed": "#000000",
        "action-primary-text": "#FFFFFF", "action-secondary": "#FFFFFF", "action-secondary-hover": ink["100"],
        "action-secondary-text": "#000000", "action-disabled": ink["200"], "action-disabled-text": ink["500"],
        "focus-ring": "#000000", "focus-ring-on-dark": "#FFFFFF", "brand-scrawl": ink["500"], "brand-tint": ink["100"],
    }
    wl = ["/* GENERATED by tools/build_tokens.py. Wireframe mode: add data-mode=\"wire\" to <html>. */",
          '[data-mode="wire"] {']
    wl += [f"  --color-{k}: {v};" for k, v in wire.items()]
    wl += ["}",
           '[data-mode="wire"] img, [data-mode="wire"] video, [data-mode="wire"] picture { visibility: hidden; }',
           '[data-mode="wire"] [data-media-slot] { background: repeating-linear-gradient(45deg, #EEF0F4 0 10px, #E2E5EB 10px 20px); }',
           '[data-mode="wire"] [data-media-slot]::after { content: attr(data-media-slot); font: 500 12px/1.2 var(--font-family-sans); color: #3C4350; padding: 8px; }']
    with open(os.path.join(OUT, "wire.css"), "w") as f:
        f.write("\n".join(wl) + "\n")

    # Tailwind v4 theme. Literal values, so Tailwind owns these variables; roles reference
    # the core/ramp variables, so wire mode (which overrides roles) still works at runtime.
    lookup = {}
    for name, v in flatten(color, "color"):
        if not name.startswith("color-role-") and v != "TBC":
            lookup[v.upper()] = lookup.get(v.upper(), name)
    tw = ["/* GENERATED by tools/build_tokens.py. Tailwind v4: @import \"tailwindcss\"; then this file. */", "@theme {"]
    for name, v in flatten(color, "color"):
        if v == "TBC":
            continue
        if name.startswith("color-role-"):
            role = name.replace("color-role-", "color-")
            ref = lookup.get(v.upper())
            tw.append(f"  --{role}: {'var(--' + ref + ')' if ref else v};")
        else:
            tw.append(f"  --{name}: {v};")
    tw.append(f"  --font-sans: {base['font']['family']['sans']['$value']};")
    for k, t in base["space"].items():
        if not k.startswith("$"):
            tw.append(f"  --spacing-{k}: {t['$value']};")
    for k, t in base["radius"].items():
        if not k.startswith("$"):
            tw.append(f"  --radius-{k}: {t['$value']};")
    for k, t in base["breakpoint"].items():
        if not k.startswith("$"):
            tw.append(f"  --breakpoint-{k}: {t['$value']};")
    tw.append("}")
    with open(os.path.join(OUT, "tailwind-theme.css"), "w") as f:
        f.write("\n".join(tw) + "\n")
    print("wrote", os.listdir(OUT))


if __name__ == "__main__":
    main()
